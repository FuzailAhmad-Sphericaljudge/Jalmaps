export function writeReportsI18n(): void {
  for (const locale of locales) {
    const localeDir = path.join(MESSAGES_DIR, locale);
    if (!fs.existsSync(localeDir)) {
      fs.mkdirSync(localeDir, { recursive: true });
    }
    const filePath = path.join(localeDir, "reports.json");
    const data = translations[locale] ?? translations.en;
    fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + "\n", "utf8");
    console.log(`[i18n] Wrote ${filePath}`);
  }
}

if (process.argv[1]?.endsWith("add-reports-i18n.ts")) {
  writeReportsI18n();
}
